    def choice_file(self, models):
        p = os.path.join(self.tmp, "gpu-choice.json")
        gp.save_choice({"version": 1, "updated_at": "x", "models": models}, p)
        return p

    def gen(self, devices, choice, user=None, name="out", **opts):
        ui = os.path.join(self.tmp, name + ".user.ini")
        if user is not None:
            with open(ui, "w", encoding="utf-8") as f:
                f.write(user)
        out = os.path.join(self.tmp, name)
        prof = gp.generate(REAL_MODELS, out, gp.Options(**opts), user_ini=ui, choice=choice,
                           discovery=(devices, "simulate", "fp"))
        with open(os.path.join(out, gp.PRESET_NAME), "rb") as f:
            raw = f.read()
        return prof, raw, gp.parse_ini(raw.decode("utf-8"))[0]

    def test_zero_regression_on_this_machine(self):
        none_file = os.path.join(self.tmp, "no-such-choice.json")
        prof, raw, _ = self.gen(gpus(RTX1000), none_file, name="a")
        self.assertEqual(raw.decode("utf-8"), TODAY_PRESET)
        self.assertFalse(raw.startswith(b"\xef\xbb\xbf"))
        # --choice none ให้ผลเหมือนกัน
        prof_none, raw_none, _ = self.gen(gpus(RTX1000), None, name="b")
        self.assertEqual(raw_none, raw)
        # เลือก "ทุกโมเดลใช้ GPU ในเครื่อง" (= ทุก GPU ที่มี) หรือ auto ทั้งหมด → preset เดิมทุกค่า
        ids = [ID27, IDCODER, IDOSS, ID4B]
        _, _, sec_same = self.gen(gpus(RTX1000), self.choice_file({m: [K1000] for m in ids}), name="c")
        self.assertEqual(sec_same, gp.parse_ini(TODAY_PRESET)[0])
        _, raw_auto, _ = self.gen(gpus(RTX1000), self.choice_file({m: "auto" for m in ids}), name="d")
        self.assertEqual(raw_auto, raw)
        # ตัวเลขใน placement เท่าเดิม ต่างแค่ป้ายที่เพิ่ม
        for mid, p in prof["placement"].items():
            core = {k: v for k, v in p.items() if k not in gp._CHOICE_FIELDS}
            core_none = {k: v for k, v in prof_none["placement"][mid].items() if k not in gp._CHOICE_FIELDS}
            self.assertEqual(core, core_none)
            self.assertEqual(p["source"], "auto")
        self.assertEqual(prof["choice"], {"path": none_file, "sha1": None, "models": {}})
        self.assertIsNone(prof_none["choice"])

