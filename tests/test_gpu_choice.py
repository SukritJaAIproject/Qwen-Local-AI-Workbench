class ReadChoiceTests(TmpDir):
    def write(self, content, name="gpu-choice.json", raw=False):
        p = os.path.join(self.tmp, name)
        with open(p, "wb") as f:
            f.write(content if raw else json.dumps(content, ensure_ascii=False).encode("utf-8"))
        return p

    def test_missing_file_is_all_auto(self):
        w = []
        info = gp.read_choice(os.path.join(self.tmp, "nope.json"), w)
        self.assertEqual(info["models"], {})
        self.assertIsNone(info["sha1"])
        self.assertEqual(w, [])
        self.assertIsNone(gp.read_choice("none", w))
        self.assertIsNone(gp.read_choice(None, w))

    def test_bad_json_is_ignored_with_thai_warning(self):
        for content in (b"{nope", b"\xff\xfe\x00garbage", b""):
            w = []
            info = gp.read_choice(self.write(content, raw=True), w)
            self.assertEqual(info["models"], {})
            self.assertEqual(info["error"], "invalid-json")
            self.assertTrue(any("อ่านไม่ออก" in x for x in w), w)

    def test_unknown_shape_is_ignored(self):
        for doc in ([1, 2], {"models": [ID4B]}, {"version": 2, "models": {ID4B: "cpu"}}, "cpu"):
            w = []
            info = gp.read_choice(self.write(doc), w)
            self.assertEqual(info["models"], {}, doc)
            self.assertEqual(info["error"], "bad-shape")
            self.assertTrue(w)

    def test_bad_entries_dropped_good_entries_kept(self):
        doc = {"version": 1, "models": {ID4B: "CPU", IDOSS: {"x": 1}, IDCODER: [], ID27: [K4090, K4090],
                                        "Other": ["x" * 121], "Fine": [K4090, K1000], "Auto": " auto "}}
        w = []
        info = gp.read_choice(self.write(doc), w)
        self.assertEqual(info["models"], {ID4B: "cpu", "Fine": [K4090, K1000], "Auto": "auto"})
        self.assertEqual(len(w), 4, w)
        self.assertTrue(info["sha1"])

    def test_bom_is_accepted(self):
        p = self.write(b"\xef\xbb\xbf" + json.dumps({"models": {ID4B: "cpu"}}).encode("utf-8"), raw=True)
        self.assertEqual(gp.read_choice(p, [])["models"], {ID4B: "cpu"})

    def test_deeply_nested_json_is_ignored_not_a_crash(self):
        # [[[[... ลึกเกินที่ json ของ Python รับได้ = RecursionError (ไม่ใช่ ValueError) — เดิมหลุดไปล้ม generate()
        # แล้วตัวเปิดถอยไปค่าแบบเดิมทั้งชุด รายงานว่า failed ทั้งที่แค่ควรไม่ใช้ไฟล์นี้
        for content in (b"[" * 5000, b'{"version": 1, "models": {"x": ' + b"[" * 100000 + b"}}"):
            w = []
            info = gp.read_choice(self.write(content, raw=True), w)
            self.assertEqual(info["error"], "invalid-json")
            self.assertEqual(info["models"], {})
            self.assertTrue(any("อ่านไม่ออก" in x for x in w), w)

    def test_huge_file_is_ignored(self):
        doc = {"version": 1, "models": {ID4B: "cpu"}, "pad": "x" * (gp.CHOICE_FILE_MAX + 10)}
        w = []
        info = gp.read_choice(self.write(doc), w)
        self.assertEqual((info["error"], info["models"], info["sha1"]), ("too-large", {}, None))
        self.assertTrue(any("ใหญ่เกิน" in x for x in w), w)
        # ไฟล์ขนาดที่ hub เขียนได้จริง (โมเดลเยอะ key ยาวสุด) ยังอ่านได้ปกติ
        big = {"version": 1, "models": {"M%03d" % i: ["G" * 118 + "%02d" % j for j in range(8)] for i in range(150)}}
        info = gp.read_choice(self.write(big), [])
        self.assertEqual(len(info["models"]), 150)
        self.assertNotIn("error", info)


class ValidateChoiceTests(TmpDir):
    IDS = [ID27, IDCODER, IDOSS, ID4B]
    KEYS = [K1000, K4090]

    def bad(self, doc, keys=KEYS):
        with self.assertRaises(ValueError) as cm:
            gp.validate_choice(doc, self.IDS, keys)
        msg = str(cm.exception)
        self.assertIn(" / ", msg)                        # "ไทย / English" ส่งกลับใน 400 ได้เลย
        self.assertTrue(cm.exception.th and cm.exception.en)
        return msg

    def test_valid_doc(self):
        doc = gp.validate_choice({"models": {ID27: [K4090], ID4B: "CPU", IDOSS: "auto"}, "junk": 1},
                                 self.IDS, self.KEYS)
        self.assertEqual(doc["version"], 1)
        self.assertTrue(doc["updated_at"])
        self.assertEqual(doc["models"], {ID27: [K4090], ID4B: "cpu", IDOSS: "auto"})
        self.assertEqual(gp.validate_choice({"models": {}}, self.IDS, self.KEYS)["models"], {})
        # known_keys = None → ไม่เช็กว่ามีการ์ดนี้
        self.assertEqual(gp.validate_choice({"models": {ID4B: ["RTX 9999"]}}, self.IDS, None)["models"],
                         {ID4B: ["RTX 9999"]})

    def test_unknown_model(self):
        self.assertIn("NoSuch", self.bad({"models": {"NoSuch": "cpu"}}))

    def test_unknown_shape(self):
        self.bad([])
        self.bad({"models": [ID4B]})
        self.bad({})
        self.bad({"models": {ID4B: "gpu"}})
        self.bad({"models": {ID4B: 3}})
        self.bad({"models": {ID4B: {"device": "CUDA0"}}})
        self.bad({"models": {ID4B: [1]}})
        self.bad({"models": {ID4B: [""]}})

    def test_list_length(self):
        self.bad({"models": {ID4B: []}})
        keys = ["G%d" % i for i in range(9)]
        self.bad({"models": {ID4B: keys}}, keys)
        self.assertEqual(len(gp.validate_choice({"models": {ID4B: keys[:8]}}, self.IDS, keys)["models"][ID4B]), 8)

    def test_too_long_key(self):
        k = "N" * 121
        self.bad({"models": {ID4B: [k]}}, None)
        self.bad({"models": {ID4B: [k]}}, [k])
        gp.validate_choice({"models": {ID4B: ["N" * 120]}}, self.IDS, None)

    def test_duplicates(self):
        self.assertIn("ซ้ำ", self.bad({"models": {ID4B: [K4090, K4090]}}))

    def test_unknown_gpu(self):
        self.bad({"models": {ID4B: [K4060]}})

    def test_long_input_not_echoed_in_full(self):
        msg = self.bad({"models": {"Z" * 5000: "cpu"}})
        self.assertLess(len(msg), 400)

    def test_deep_value_gives_choice_error_not_recursion_error(self):
        # ค่าที่ซ้อนลึกมาก: ข้อความผิดพลาด (_brief) เคยโยน RecursionError ออกมาแทน ChoiceError
        deep = cur = []
        for _ in range(100000):
            nxt = []
            cur.append(nxt)
            cur = nxt
        self.assertEqual(gp._brief(deep), "<list>")
        self.bad({"models": {ID4B: [deep]}})
        self.bad({"models": {ID4B: {"x": deep}}})

    def test_save_choice_roundtrip_no_bom(self):
        p = os.path.join(self.tmp, "sub", "gpu-choice.json")
        doc = gp.validate_choice({"models": {ID27: [K4090], ID4B: "cpu"}}, self.IDS, self.KEYS)
        gp.save_choice(doc, p)
        with open(p, "rb") as f:
            raw = f.read()
        self.assertFalse(raw.startswith(b"\xef\xbb\xbf"))
        self.assertEqual(gp.read_choice(p, [])["models"], doc["models"])
        self.assertEqual(sorted(os.listdir(os.path.dirname(p))), ["gpu-choice.json"])     # ไม่มีไฟล์ชั่วคราวค้าง


