        self.assertEqual(set(cat), set(self.WANT))
        for mid, want in self.WANT.items():
            for k, v in want.items():
                self.assertEqual(cat[mid][k], v, (mid, k))
            self.assertEqual(cat[mid]["primary"], mid == ID27)

