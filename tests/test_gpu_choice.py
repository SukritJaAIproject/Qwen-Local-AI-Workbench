class ApplyChoiceTests(unittest.TestCase):
    def test_no_choice_only_labels(self):
        devs = keyed(RTX1000, RTX4090)
        base = gp.plan(devs, real_models(), gp.Options())
        res, w = choose(keyed(RTX1000, RTX4090), {})
        self.assertEqual(res["sections"], base["sections"])
        self.assertEqual(w, [])
        for mid, p in res["placement"].items():
            self.assertEqual((p["source"], p["choice"], p["choice_missing"]), ("auto", None, False))
            self.assertEqual(p["auto"], {"devices": base["placement"][mid]["devices"],
                                         "ctx": base["placement"][mid]["ctx"],
                                         "vision": base["placement"][mid]["vision"]})
            core = {k: v for k, v in p.items() if k not in gp._CHOICE_FIELDS}
            self.assertEqual(core, base["placement"][mid])

    def test_cpu(self):
        res, _ = choose(keyed(RTX1000), {ID4B: "cpu", ID27: "cpu"})
        self.assertEqual(res["sections"][ID4B], {"device": "none"})
        self.assertEqual(res["sections"][ID27], {"device": "none"})
        p = res["placement"][ID4B]
        self.assertEqual((p["devices"], p["source"], p["choice"]), ([], "choice", "cpu"))
        self.assertFalse(res["placement"][ID27]["vision"])
        self.assertIn("CPU", p["note_th"])
        # ไม่มี GPU เลย: สั่ง CPU ชัดๆ ก็ยังเขียน device = none
        res2, _ = choose([], {ID4B: "cpu"})
        self.assertEqual(res2["sections"][ID4B], {"device": "none"})

    def test_single_gpu(self):
        res, _ = choose(keyed(RTX1000, RTX4090), {ID4B: [K4090]})
        self.assertEqual(res["sections"][ID4B], {"device": "CUDA1"})
        p = res["placement"][ID4B]
        self.assertEqual(p["devices"], ["CUDA1"])
        self.assertEqual(p["auto"]["devices"], ["CUDA0"])        # แผนอัตโนมัติให้ RTX 1000 (4090 กันไว้ให้ 27B)
        self.assertTrue(p["shared_with_primary"])                # ใช้การ์ดร่วมกับ 27B ที่จองไว้
        # 27B ยังเป็น auto → ไม่เปลี่ยน (หน้าเว็บบอก "อัตโนมัติ — 4090" ไว้ ต้องตรงกับที่เกิดจริง)
        self.assertEqual(res["sections"][ID27], {"device": "CUDA1", "ctx-size": "65536", "mmproj": MMPROJ})

    def test_multi_gpu_largest_first(self):
        res, _ = choose(keyed(RTX1000, RTX4090), {IDCODER: [K1000, K4090]})
        self.assertEqual(res["sections"][IDCODER], {"device": "CUDA1,CUDA0"})
        self.assertEqual(res["placement"][IDCODER]["devices"], ["CUDA1", "CUDA0"])
        # ทุก GPU ตามลำดับปกติอยู่แล้ว = เท่ากับไม่ระบุ → ไม่เขียน device
        res2, _ = choose(keyed(RTX4090, RTX1000), {IDCODER: [K1000, K4090]})
        self.assertNotIn("device", res2["sections"][IDCODER])
        self.assertEqual(res2["placement"][IDCODER]["devices"], ["CUDA0", "CUDA1"])
        # สามใบ: 4090 → 4060 Ti → RTX 1000 ไม่ว่าเลข CUDA จะเป็นอะไร
        tri = load_fixture("tri_r1k_4090_4060")
        res3, _ = choose(tri, {ID4B: [K1000, K4060, K4090]})
        by = {d["id"]: d["short"] for d in tri}
        self.assertEqual([by[i] for i in res3["placement"][ID4B]["devices"]], ["RTX 4090", "RTX 4060 Ti", "RTX 1000 Ada"])

    def test_missing_key_falls_back_to_auto(self):
        base = gp.plan(keyed(RTX1000), real_models(), gp.Options())
        res, w = choose(keyed(RTX1000), {ID27: [K4090], ID4B: [K4060]})
        self.assertEqual(res["sections"], base["sections"])          # ถอด eGPU แล้ว = แผนอัตโนมัติ
        for mid in (ID27, ID4B):
            p = res["placement"][mid]
            self.assertTrue(p["choice_missing"])
            self.assertEqual(p["source"], "auto")
            self.assertEqual(p["devices"], ["CUDA0"])
        self.assertEqual(res["placement"][ID27]["choice"], [K4090])
        self.assertEqual(len(w), 2)
        self.assertTrue(all("ไม่ได้ต่ออยู่" in x for x in w))
        self.assertEqual(res["choices_applied"], [])

    def test_partly_missing_keys_use_the_rest(self):
        res, w = choose(keyed(RTX1000, RTX4090), {IDCODER: [K4090, K4060]})
        p = res["placement"][IDCODER]
        self.assertEqual(p["devices"], ["CUDA1"])
        self.assertEqual(p["choice_dropped"], [K4060])
        self.assertFalse(p["choice_missing"])
        self.assertTrue(w)

    def test_primary_alone_on_4090_gets_64k_and_vision(self):
        for devs in (keyed(RTX1000, RTX4090), keyed(RTX4090, RTX1000), load_fixture("tri_r1k_4060_4090")):
            res, _ = choose(devs, {ID27: [K4090]})
            fit = next(d["id"] for d in devs if d["key"] == K4090)
            self.assertEqual(res["sections"][ID27], {"device": fit, "ctx-size": "65536", "mmproj": MMPROJ})
            p = res["placement"][ID27]
            self.assertEqual((p["ctx"], p["vision"], p["source"]), (65536, True, "choice"))
            self.assertTrue(p["fits_fully"])
        # 4090 ใบเดียว: โมเดลอื่นใช้การ์ดร่วมแบบ -fit (ไม่ได้ผูก) → ยังนับว่าอยู่คนเดียว = เท่ากับ auto
        auto = gp.plan(keyed(RTX4090), real_models(), gp.Options())
        res, _ = choose(keyed(RTX4090), {ID27: [K4090]})
        self.assertEqual(res["sections"][ID27], auto["sections"][ID27])

    def test_primary_and_coder_both_on_4090_get_32k_no_vision(self):
        res, _ = choose(keyed(RTX1000, RTX4090), {ID27: [K4090], IDCODER: [K4090]})
        self.assertEqual(res["sections"][ID27], {"device": "CUDA1"})
        self.assertEqual(res["sections"][IDCODER], {"device": "CUDA1"})
        p = res["placement"][ID27]
        self.assertEqual((p["ctx"], p["vision"]), (32768, False))
