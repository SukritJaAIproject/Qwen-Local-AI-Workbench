# ================================================================ GPU key
class GpuKeyTests(unittest.TestCase):
    def test_key_is_full_name(self):
        devs = keyed(RTX1000, RTX4090)
        self.assertEqual([d["key"] for d in devs], [K1000, K4090])

    def test_renumbering_keeps_key(self):
        # 4090 เป็น CUDA0 ในรอบหนึ่ง และ CUDA2 อีกรอบ (เสียบ eGPU ต่างลำดับ) — key ต้องเท่าเดิม
        a = {d["id"]: d["key"] for d in load_fixture("tri_4090_r1k_4060")}
        b = {d["id"]: d["key"] for d in load_fixture("tri_r1k_4060_4090")}
        self.assertEqual(a["CUDA0"], K4090)
        self.assertEqual(b["CUDA2"], K4090)
        self.assertEqual(sorted(a.values()), sorted(b.values()))

    def test_duplicate_names_numbered_in_pci_bus_order(self):
        devs = load_fixture("r1k_two_4090")                  # bus 2C = CUDA1, bus 3D = CUDA2
        self.assertEqual([d["key"] for d in devs], [K1000, K4090, K4090 + " #2"])
        # เลข CUDA สลับกัน (id กลับด้าน) แต่ bus เดิม → ใบเดิมได้ key เดิม
        swapped = [dict(d) for d in devs]
        swapped[1]["id"], swapped[2]["id"] = "CUDA2", "CUDA1"
        swapped = [swapped[0], swapped[2], swapped[1]]
        for d in swapped:
            d.pop("key")
        gp.assign_gpu_keys(swapped)
        by_bus = {d["pci_bus_id"]: d["key"] for d in swapped}
        self.assertEqual(by_bus["00000000:2C:00.0"], K4090)
        self.assertEqual(by_bus["00000000:3D:00.0"], K4090 + " #2")

    def test_unplugging_the_first_identical_card_is_a_known_limit(self):
        # ข้อจำกัดที่ยอมรับไว้ (ดู assign_gpu_keys): " #2" คือลำดับในกลุ่มชื่อเดียวกันที่ต่ออยู่ตอนนั้น ไม่ใช่ตัวตนของพอร์ต
        # ถอดใบ bus ต่ำกว่าออก ใบที่เหลือได้ชื่อเฉยๆ — ที่เลือก " #2" ไว้กลายเป็น "ไม่ได้ต่ออยู่" (อัตโนมัติ + บอกผู้ใช้)
        two = load_fixture("r1k_two_4090")                   # bus 2C = 4090, bus 3D = 4090 #2
        self.assertEqual({d["pci_bus_id"]: d["key"] for d in two if "4090" in d["key"]},
                         {"00000000:2C:00.0": K4090, "00000000:3D:00.0": K4090 + " #2"})
        left = [dict(d) for d in two if d["pci_bus_id"] != "00000000:2C:00.0"]
        for d in left:
            d.pop("key")
        gp.assign_gpu_keys(left)
        self.assertEqual({d["pci_bus_id"]: d["key"] for d in left if "4090" in d["key"]}, {"00000000:3D:00.0": K4090})
        res, w = choose(left, {ID27: [K4090 + " #2"]})
        self.assertTrue(res["placement"][ID27]["choice_missing"])
        self.assertEqual(res["placement"][ID27]["source"], "auto")

    def test_duplicate_names_without_bus_ids_use_list_order(self):
        devs = [gp._finish_device({"id": "CUDA%d" % i, "name": K4090, "total_mib": 24564}) for i in range(3)]
        gp.assign_gpu_keys(devs)
        self.assertEqual([d["key"] for d in devs], [K4090, K4090 + " #2", K4090 + " #3"])

    def test_bus_sort_is_numeric(self):
        devs = [gp._finish_device({"id": "CUDA0", "name": K4090, "total_mib": 1, "pci_bus_id": "00000000:10:00.0"}),
                gp._finish_device({"id": "CUDA1", "name": K4090, "total_mib": 1, "pci_bus_id": "00000000:09:00.0"})]
        gp.assign_gpu_keys(devs)
        self.assertEqual(devs[1]["key"], K4090)            # 0x09 < 0x10
        self.assertEqual(devs[0]["key"], K4090 + " #2")

    def test_keys_are_valid_choice_keys(self):
        long_name = "NVIDIA " + "X" * 300
        devs = [gp._finish_device({"id": "CUDA%d" % i, "name": long_name, "total_mib": 1}) for i in range(2)]
        gp.assign_gpu_keys(devs)
        keys = [d["key"] for d in devs]
        self.assertTrue(all(len(k) <= gp.CHOICE_KEY_MAX for k in keys))
        self.assertEqual(len(set(keys)), 2)
        gp.validate_choice({"models": {ID4B: keys}}, [ID4B], keys)      # ต้องผ่านการตรวจของ hub


